import numpy as np


def hf_hartmann(x):
    A = np.array([[10. , 3.0, 17. , 3.5, 1.7, 8.0],
                       [0.05, 10., 17. , 0.1, 8.0, 14.],
                       [3.0 , 3.5, 1.7 , 10., 17., 8.0],
                       [17. , 8.0, 0.05, 10., 0.1, 14.]])
    P = np.array([[1312., 1696., 5569., 124. , 8283., 5886.],
                       [2329., 4135., 8307., 3736., 1004., 9991.],
                       [2348., 1451., 3522., 2883., 3047., 6650.],
                       [4047., 8828., 8732., 5743., 1091., 381.0]])
    P = 1.e-4 * P
    alpha = np.array([1.0, 1.2, 3.0, 3.2])
    
    y = np.zeros(1)
    for i in range(len(alpha)):
      y[0] += -1.0 * alpha[i] * np.exp( -1.0 * np.inner(A[i,:], (x - P[i,:])**2.))
    y = y.reshape(-1, 1)
    return y


def fexp(x):
    y = (np.exp(-4./9.) + (np.exp(-4./9.)*(x + 4.) / 9.))**9
    return y

